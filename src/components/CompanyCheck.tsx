const cleanDomainString = (raw: string): string => {
  return raw
    .trim()
    .toLowerCase()
    .replace(/^https?:\/\//, '')
    .replace(/^www\./, '')
    .split('/')[0]
    .split('?')[0];
};

// ─────────────────────────────────────────────────────────
// Core Analysis Functions
// ─────────────────────────────────────────────────────────

function analyzeDomain(domainInput: string): DomainAnalysisResult | null {
  const domain = cleanDomainString(domainInput);
  if (!domain) return null;

  const parts = domain.split('.');
  const tld = parts[parts.length - 1].toLowerCase();

  const suspiciousPatterns: DomainAnalysisResult['suspiciousPatterns'] = [];

  SUSPICIOUS_DOMAIN_PATTERNS.forEach(({ label, pattern, risk, reason }) => {
    if (pattern.test(domain)) {
      suspiciousPatterns.push({ label, risk, reason });
    }
  });

  const tldRisk: DomainAnalysisResult['tldRisk'] = SUSPICIOUS_TLDS.includes(tld)
    ? 'danger'
    : REPUTABLE_TLDS.includes(tld)
    ? 'safe'
    : 'warning';

  if (tldRisk === 'danger' && !suspiciousPatterns.some(p => p.label.includes('TLD'))) {
    suspiciousPatterns.push({
      label: `Suspicious TLD (.${tld})`,
      risk: 'danger',
      reason: `The .${tld} TLD is commonly used for disposable or phishing domains. Verify through WHOIS.`
    });
  }

  // Lookalike keyword check in domain name (excluding TLD)
  const domainName = parts.slice(0, -1).join('.').toLowerCase();
  const foundKeywords = LOOKALIKE_KEYWORDS.filter(kw => domainName.includes(kw));

  // Only flag lookalike keywords if domain also has other suspicious traits (hyphen, mismatch, etc.)
  const hasHyphen = domainName.includes('-');
  const hasLookalikeKeyword = foundKeywords.length > 0 && hasHyphen;
  if (hasLookalikeKeyword && !suspiciousPatterns.some(p => p.label === 'Hyphenated Recruitment Keyword')) {
    suspiciousPatterns.push({
      label: 'Recruitment Keyword in Hyphenated Domain',
      risk: 'warning',
      reason: `Domain "${domain}" contains recruitment keywords (${foundKeywords.join(', ')}) combined with hyphens — a pattern used in impersonation attacks.`
    });
  }

  const hasAnyDanger = suspiciousPatterns.some(p => p.risk === 'danger') || tldRisk === 'danger';
  const hasAnyWarning = suspiciousPatterns.some(p => p.risk === 'warning') || tldRisk === 'warning';

  return {
    suspiciousPatterns,
    tldRisk,
    tld,
    hasLookalikeKeyword,
    lookalikeKeywords: foundKeywords,
    overallRisk: hasAnyDanger ? 'danger' : hasAnyWarning ? 'warning' : 'safe'
  };
}

function analyzeLookalikeDomain(officialDomain: string, emailDomain: string): {
  isLookalike: boolean;
  details: string;
  risk: 'warning' | 'danger' | 'safe';
} {
  if (!officialDomain || !emailDomain || officialDomain === emailDomain) {
    return { isLookalike: false, details: '', risk: 'safe' };
  }

  const officialBase = officialDomain.split('.')[0];
  const emailBase = emailDomain.replace(/\.[^.]+$/, '');

  // Check if email domain contains the official brand name + extra keywords
  const hasOfficialBrand = emailBase.includes(officialBase);
  const hasLookalike = hasOfficialBrand && LOOKALIKE_KEYWORDS.some(kw => emailBase.includes(kw));

  if (hasLookalike) {
    return {
      isLookalike: true,
      details: `"@${emailDomain}" contains the brand name "${officialBase}" with appended recruitment keywords — a classic lookalike domain used to impersonate "${officialDomain}".`,
      risk: 'danger'
    };
  }

  // Levenshtein-like: check if emailBase is within edit distance 2 of officialBase (simple heuristic)
  const longer = officialBase.length > emailBase.length ? officialBase : emailBase;
  const shorter = officialBase.length > emailBase.length ? emailBase : officialBase;
  let differences = 0;
  for (let i = 0; i < Math.min(longer.length, shorter.length); i++) {
    if (longer[i] !== shorter[i]) differences++;
  }
  differences += Math.abs(longer.length - shorter.length);

  if (differences <= 2 && differences > 0) {
    return {
      isLookalike: true,
      details: `"@${emailDomain}" closely resembles the official domain "${officialDomain}" (possible character substitution or addition). This is a typosquatting warning.`,
      risk: 'warning'
    };
  }

  return { isLookalike: false, details: '', risk: 'safe' };
}

function analyzeUrl(url: string): UrlSafetyResult | null {
  const trimmed = url.trim();
  if (!trimmed) return null;

  const findings: UrlSafetyResult['findings'] = [];

  UNSAFE_URL_PATTERNS.forEach(({ label, pattern, risk, reason }) => {
    if (pattern.test(trimmed)) {
      findings.push({ label, risk, reason });
    }
  });

  const hasAnyDanger = findings.some(f => f.risk === 'danger');
  const hasAnyWarning = findings.some(f => f.risk === 'warning');

  return {
    findings,
    overallRisk: hasAnyDanger ? 'danger' : hasAnyWarning ? 'warning' : 'safe'
  };
}

